#!/usr/bin/env python3
"""Reproducible app-owned observer. Compile against pinned official SMAPI, never ship its DLLs."""
import argparse, hashlib, io, json, subprocess, zipfile
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
HERE=Path(__file__).resolve().parent
OUT=ROOT/'app/src/main/assets/smapi-diagnostics'
GENERATED=ROOT/'app/src/main/java/dev/aura/console/runtime/SmapiProbeBinary.kt'
def sha(p): return hashlib.sha256(p.read_bytes()).hexdigest()
def main():
    p=argparse.ArgumentParser(); p.add_argument('--toolchain',type=Path); p.add_argument('--check',action='store_true'); a=p.parse_args()
    if a.check:
        r=json.loads((HERE/'build.json').read_text())
        for name,digest in r['sources'].items(): assert sha(HERE/name)==digest,name
        for name,digest in r['assets'].items(): assert sha(OUT/name)==digest and digest in GENERATED.read_text(),name
        print('SMAPI diagnostics source/assets contract verified'); return
    t=a.toolchain; assert t
    for name,item in json.loads((HERE/'sources.json').read_text()).items(): assert sha(t/name)==item['sha256'],name
    with zipfile.ZipFile(t/'compiler.zip') as z:
        for n in z.namelist():
            if n.startswith('tasks/netcore/') and not n.endswith('/'):
                assert (t/'compiler'/n).read_bytes()==z.read(n),n
    with zipfile.ZipFile(t/'net6ref.zip') as z:
        for n in z.namelist():
            if n.startswith('ref/net6.0/') and n.endswith('.dll'): assert (t/n).read_bytes()==z.read(n),n
    with zipfile.ZipFile(t/'smapi.zip') as outer:
        with zipfile.ZipFile(io.BytesIO(outer.read('SMAPI 4.5.2 installer/internal/windows/install.dat'))) as z:
            for path in ['StardewModdingAPI.dll','smapi-internal/SMAPI.Toolkit.CoreInterfaces.dll']:
                assert (t/Path(path).name).read_bytes()==z.read(path)
    refs=list((t/'ref/net6.0').glob('*.dll'))+[t/'StardewModdingAPI.dll',t/'SMAPI.Toolkit.CoreInterfaces.dll']
    OUT.mkdir(parents=True,exist_ok=True)
    args=[str(t/'runtime/dotnet'),str(t/'compiler/tasks/netcore/bincore/csc.dll'),'-nologo','-target:library','-langversion:12',
          '-nullable:enable','-deterministic+','-optimize+','-debug-','-pathmap:'+str(ROOT)+'=/src',
          '-out:'+str(OUT/'Aura.Diagnostics.dll')]+['-r:'+str(r) for r in refs]+[str(HERE/'Probe.cs')]
    subprocess.run(args,check=True,env=__import__('os').environ|{'DOTNET_ROLL_FORWARD':'Major'})
    (OUT/'manifest.json').write_bytes((HERE/'manifest.json').read_bytes())
    assets={n:sha(OUT/n) for n in ['Aura.Diagnostics.dll','manifest.json']}
    r={'sources':{n:sha(HERE/n) for n in ['Probe.cs','manifest.json','build.py','sources.json']},'assets':assets,
       'smapiVersion':'4.5.2','smapiSha256':sha(t/'smapi.zip'),'compiler':'Microsoft.Net.Compilers.Toolset 4.11.0',
       'targetFramework':'net6.0','deviceTested':False}
    (HERE/'build.json').write_text(json.dumps(r,indent=2)+'\n')
    GENERATED.write_text('package dev.aura.console.runtime\n\n// Generated by tools/smapi-diagnostics/build.py.\ninternal object SmapiProbeBinary {\n    val assets = mapOf(\n'+',\n'.join('        "'+n+'" to "'+v+'"' for n,v in assets.items())+'\n    )\n}\n')
if __name__=='__main__':main()
