#!/usr/bin/env python3
"""Build the bounded SMAPI input relay. No C runtime; no shell imports."""
import argparse, hashlib, json, re, subprocess, tempfile
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
SOURCE = HERE / 'relay.c'
BINARY = ROOT / 'app/src/main/assets/mod-console/aura-mod-console.exe'
KOTLIN = ROOT / 'app/src/main/java/dev/aura/console/runtime/ModConsoleBinary.kt'
def digest(path): return hashlib.sha256(path.read_bytes()).hexdigest()
def main():
    p = argparse.ArgumentParser(); p.add_argument('--llvm', type=Path); p.add_argument('--check', action='store_true'); args=p.parse_args()
    if args.check:
        record=json.loads((HERE/'build.json').read_text())
        assert record['sourceSha256']==digest(SOURCE) and record['binarySha256']==digest(BINARY)
        assert record['buildSha256']==digest(Path(__file__))
        assert record['binarySha256'] in KOTLIN.read_text()
        print('Mod console source/binary/host contract verified');return
    assert args.llvm
    imports=re.findall(r'^API \w+ (\w+)\(', SOURCE.read_text(), re.M)
    with tempfile.TemporaryDirectory(prefix='aura-mod-console-') as work:
        work=Path(work); definition=work/'kernel32.def'
        definition.write_text('LIBRARY kernel32.dll\nEXPORTS\n'+'\n'.join(imports)+'\n')
        subprocess.run([str(args.llvm/'llvm-dlltool'),'-m','i386:x86-64','-d',str(definition),'-l',str(work/'kernel32.lib')],check=True)
        subprocess.run([str(args.llvm/'clang'),'--target=x86_64-pc-windows-msvc','-c',str(SOURCE),'-o',str(work/'relay.obj'),
            '-Oz','-ffreestanding','-fno-stack-protector','-fno-ident','-Wall','-Wextra','-Werror'],check=True)
        BINARY.parent.mkdir(parents=True,exist_ok=True)
        subprocess.run([str(args.llvm/'lld-link'),str(work/'relay.obj'),str(work/'kernel32.lib'),'/entry:mainCRTStartup',
            '/subsystem:windows','/nodefaultlib','/machine:x64','/Brepro','/timestamp:0','/opt:ref','/opt:icf','/out:'+str(BINARY)],check=True)
    record=dict(sourceSha256=digest(SOURCE),buildSha256=digest(Path(__file__)),binarySha256=digest(BINARY),bytes=BINARY.stat().st_size,imports=imports,deviceTested=False)
    (HERE/'build.json').write_text(json.dumps(record,indent=2)+'\n')
    KOTLIN.write_text('package dev.aura.console.runtime\n\n// Generated by tools/mod-console/build.py.\ninternal object ModConsoleBinary {\n    const val SHA256 = "'+record['binarySha256']+'"\n}\n')
    print(json.dumps(record,indent=2))
if __name__=='__main__':main()
